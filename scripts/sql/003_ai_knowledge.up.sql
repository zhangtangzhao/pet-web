-- 003: AI 客服知识库表 + 种子数据
-- ai_knowledge.breed_id 为 NULL 表示平台通用知识（全品种适用）
-- ============================================================

CREATE TABLE IF NOT EXISTS ai_knowledge (
    id          BIGINT PRIMARY KEY,                          -- 雪花 ID（应用层生成）
    breed_id    BIGINT NULL REFERENCES breed(id),            -- NULL = 平台通用
    title       VARCHAR(128) NOT NULL,
    keywords    VARCHAR(255) NOT NULL DEFAULT '',            -- 逗号分隔，用于问答检索
    content     TEXT NOT NULL,
    sort        INT NOT NULL DEFAULT 0,
    status      SMALLINT NOT NULL DEFAULT 1,                 -- 1启用 0停用
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ai_knowledge_breed ON ai_knowledge(breed_id) WHERE status = 1;

